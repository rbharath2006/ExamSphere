
-- ============================================================
-- ExamSphere V2: Examination Management Database
-- Creates exams, questions, options, attempts, answers, results
-- ============================================================

-- ------------------------------------------------------------
-- 1. EXAMS
-- Stores examinations created by Teachers.
-- ------------------------------------------------------------

CREATE TABLE exams (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       title VARCHAR(200) NOT NULL,
                       description TEXT,
                       subject VARCHAR(120) NOT NULL,
                       instructions TEXT,

                       duration_minutes INTEGER NOT NULL,

                       starts_at TIMESTAMPTZ NOT NULL,
                       ends_at TIMESTAMPTZ NOT NULL,

                       status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

                       total_marks NUMERIC(8, 2) NOT NULL DEFAULT 0,

                       results_published_at TIMESTAMPTZ,

                       created_by BIGINT NOT NULL,

                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT fk_exams_created_by
                           FOREIGN KEY (created_by)
                               REFERENCES users(id)
                               ON DELETE RESTRICT,

                       CONSTRAINT chk_exams_title_not_empty
                           CHECK (LENGTH(BTRIM(title)) > 0),

                       CONSTRAINT chk_exams_subject_not_empty
                           CHECK (LENGTH(BTRIM(subject)) > 0),

                       CONSTRAINT chk_exams_duration
                           CHECK (duration_minutes > 0),

                       CONSTRAINT chk_exams_schedule
                           CHECK (ends_at > starts_at),

                       CONSTRAINT chk_exams_status
                           CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),

                       CONSTRAINT chk_exams_total_marks
                           CHECK (total_marks >= 0)
);

CREATE INDEX idx_exams_created_by
    ON exams(created_by);

CREATE INDEX idx_exams_status
    ON exams(status);

CREATE INDEX idx_exams_schedule
    ON exams(starts_at, ends_at);


-- ------------------------------------------------------------
-- 2. QUESTIONS
-- Stores questions belonging to examinations.
-- ------------------------------------------------------------

CREATE TABLE questions (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           exam_id BIGINT NOT NULL,

                           question_text TEXT NOT NULL,

                           question_type VARCHAR(30) NOT NULL,

                           marks NUMERIC(8, 2) NOT NULL,

                           negative_marks NUMERIC(8, 2) NOT NULL DEFAULT 0,

                           display_order INTEGER NOT NULL,

                           created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT fk_questions_exam
                               FOREIGN KEY (exam_id)
                                   REFERENCES exams(id)
                                   ON DELETE CASCADE,

                           CONSTRAINT chk_questions_text
                               CHECK (LENGTH(BTRIM(question_text)) > 0),

                           CONSTRAINT chk_questions_type
                               CHECK (question_type IN ('SINGLE_CHOICE', 'TRUE_FALSE')),

                           CONSTRAINT chk_questions_marks
                               CHECK (marks > 0),

                           CONSTRAINT chk_questions_negative_marks
                               CHECK (
                                   negative_marks >= 0
                                       AND negative_marks <= marks
                                   ),

                           CONSTRAINT chk_questions_display_order
                               CHECK (display_order > 0),

                           CONSTRAINT uq_questions_exam_order
                               UNIQUE (exam_id, display_order)
);

CREATE INDEX idx_questions_exam
    ON questions(exam_id);


-- ------------------------------------------------------------
-- 3. QUESTION OPTIONS
-- Stores the available answer choices.
-- Correct answers remain server-side and must not be exposed
-- through student-facing API responses.
-- ------------------------------------------------------------

CREATE TABLE question_options (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  question_id BIGINT NOT NULL,

                                  option_text TEXT NOT NULL,

                                  display_order INTEGER NOT NULL,

                                  is_correct BOOLEAN NOT NULL DEFAULT FALSE,

                                  CONSTRAINT fk_options_question
                                      FOREIGN KEY (question_id)
                                          REFERENCES questions(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT chk_options_text
                                      CHECK (LENGTH(BTRIM(option_text)) > 0),

                                  CONSTRAINT chk_options_display_order
                                      CHECK (display_order > 0),

                                  CONSTRAINT uq_options_question_order
                                      UNIQUE (question_id, display_order),

    -- Supports a composite foreign key from student_answers.
                                  CONSTRAINT uq_options_question_id
                                      UNIQUE (question_id, id)
);

CREATE INDEX idx_question_options_question
    ON question_options(question_id);


-- ------------------------------------------------------------
-- 4. EXAM ATTEMPTS
-- Stores each student's examination attempt.
-- Initial version allows one attempt per student per exam.
-- ------------------------------------------------------------

CREATE TABLE exam_attempts (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               exam_id BIGINT NOT NULL,

                               student_id BIGINT NOT NULL,

                               started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               expires_at TIMESTAMPTZ NOT NULL,

                               submitted_at TIMESTAMPTZ,

                               status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',

                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_attempts_exam
                                   FOREIGN KEY (exam_id)
                                       REFERENCES exams(id)
                                       ON DELETE RESTRICT,

                               CONSTRAINT fk_attempts_student
                                   FOREIGN KEY (student_id)
                                       REFERENCES users(id)
                                       ON DELETE RESTRICT,

                               CONSTRAINT chk_attempt_status
                                   CHECK (
                                       status IN (
                                                  'IN_PROGRESS',
                                                  'SUBMITTED',
                                                  'AUTO_SUBMITTED'
                                           )
                                       ),

                               CONSTRAINT chk_attempt_expiry
                                   CHECK (expires_at > started_at),

                               CONSTRAINT chk_attempt_submission_time
                                   CHECK (
                                       submitted_at IS NULL
                                           OR submitted_at >= started_at
                                       ),

                               CONSTRAINT chk_attempt_submission_status
                                   CHECK (
                                       (status = 'IN_PROGRESS' AND submitted_at IS NULL)
                                           OR
                                       (
                                           status IN ('SUBMITTED', 'AUTO_SUBMITTED')
                                               AND submitted_at IS NOT NULL
                                           )
                                       ),

                               CONSTRAINT uq_exam_student_attempt
                                   UNIQUE (exam_id, student_id)
);

CREATE INDEX idx_attempts_student
    ON exam_attempts(student_id);

CREATE INDEX idx_attempts_exam
    ON exam_attempts(exam_id);

CREATE INDEX idx_attempts_status
    ON exam_attempts(status);


-- ------------------------------------------------------------
-- 5. STUDENT ANSWERS
-- Stores answers selected by students.
-- One answer per question per attempt.
-- The selected option must belong to the same question.
-- ------------------------------------------------------------

CREATE TABLE student_answers (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 attempt_id BIGINT NOT NULL,

                                 question_id BIGINT NOT NULL,

                                 selected_option_id BIGINT NOT NULL,

                                 answered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT fk_answers_attempt
                                     FOREIGN KEY (attempt_id)
                                         REFERENCES exam_attempts(id)
                                         ON DELETE CASCADE,

                                 CONSTRAINT fk_answers_question
                                     FOREIGN KEY (question_id)
                                         REFERENCES questions(id)
                                         ON DELETE RESTRICT,

                                 CONSTRAINT fk_answers_selected_option
                                     FOREIGN KEY (question_id, selected_option_id)
                                         REFERENCES question_options(question_id, id)
                                         ON DELETE RESTRICT,

                                 CONSTRAINT uq_attempt_question_answer
                                     UNIQUE (attempt_id, question_id)
);

CREATE INDEX idx_student_answers_attempt
    ON student_answers(attempt_id);


-- ------------------------------------------------------------
-- 6. EXAM RESULTS
-- Stores automatically calculated examination results.
-- One result per examination attempt.
-- ------------------------------------------------------------

CREATE TABLE exam_results (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              attempt_id BIGINT NOT NULL,

                              total_marks NUMERIC(8, 2) NOT NULL,

                              obtained_marks NUMERIC(8, 2) NOT NULL,

                              percentage NUMERIC(5, 2) NOT NULL,

                              evaluated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_results_attempt
                                  FOREIGN KEY (attempt_id)
                                      REFERENCES exam_attempts(id)
                                      ON DELETE CASCADE,

                              CONSTRAINT uq_results_attempt
                                  UNIQUE (attempt_id),

                              CONSTRAINT chk_results_total_marks
                                  CHECK (total_marks > 0),

                              CONSTRAINT chk_results_obtained_marks
                                  CHECK (
                                      obtained_marks >= 0
                                          AND obtained_marks <= total_marks
                                      ),

                              CONSTRAINT chk_results_percentage
                                  CHECK (percentage >= 0 AND percentage <= 100)
);

CREATE INDEX idx_exam_results_attempt
    ON exam_results(attempt_id);


